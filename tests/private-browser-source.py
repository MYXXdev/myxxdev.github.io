#!/usr/bin/env python3
# MYB Private: the standalone browser app. UIKit/WebKit don't exist on this desktop toolchain, so there is no native
# desktop test for it (unlike firewall-core.m etc.) -- this file is the whole check, on the source, before CI compiles
# the real thing on a macOS/iOS SDK runner. tests/browser-policy.py already covers the injection-filter/policy side
# (Shared/MYBBrowserPolicy.h <-> MYBShieldBrowser.plist <-> MYBShieldBrowser/Tweak.xm); this file covers the app itself.
import re,sys,pathlib
ROOT=pathlib.Path(__file__).resolve().parent.parent
def R(p):return (ROOT/p).read_text(encoding='utf-8')
bad=[];total=0
def need(c,m):
    global total;total+=1
    print(('ok   ' if c else 'FAIL ')+m)
    if not c:bad.append(m)
strip=lambda t:re.sub(r'//[^\n]*','',re.sub(r'/\*.*?\*/','',t,flags=re.S))

mk=R('PrivateBrowser/Makefile')
plist=R('PrivateBrowser/Resources/Info.plist')
ctrl_raw=R('PrivateBrowser/MYBPBBrowserController.m')
ctrl=strip(ctrl_raw)
appdel=strip(R('PrivateBrowser/MYBPBAppDelegate.m'))
appdel_raw=R('PrivateBrowser/MYBPBAppDelegate.m')
header=strip(R('PrivateBrowser/MYBPBBrowserController.h'))
main_mk=R('Makefile')
ci=R('.github/workflows/build-deb-only.yml')
policy=R('Shared/MYBBrowserPolicy.h')
filt=R('Companions/MYBShieldBrowser/MYBShieldBrowser.plist')

# ---- it's a real standalone app, built the Theos way, not a bundle/tweak masquerading as one ----
need('include $(THEOS_MAKE_PATH)/application.mk' in mk,'built with application.mk -- a real .app, not a tweak or preference bundle')
need(re.search(r'APPLICATION_NAME\s*=\s*MYBPrivateBrowser',mk) is not None,'application instance is named')
need('main.m' in mk and 'MYBPBAppDelegate.m' in mk and 'MYBPBBrowserController.m' in mk,'every source file is actually compiled in')
need('WebKit' in mk and 'UIKit' in mk,'links WebKit and UIKit')
need('PrivateBrowser' in main_mk,'wired into the top-level package as a subproject, so it actually ships in the .deb')

# ---- identity: its own bundle ID, matching what the injection policy expects, with an icon and a name ----
need('net.myxxdev.mybloxxbrowser' in plist,"the app's own bundle identifier matches Shared/MYBBrowserPolicy.h exactly")
need('net.myxxdev.mybloxxbrowser' in policy and 'net.myxxdev.mybloxxbrowser' in filt,'the policy table and the injection filter both know about this app (tests/browser-policy.py enforces they stay in sync)')
need('MYB Private' in plist,'has a real display name for the home screen')
need('AppIcon' in plist,'references an app icon')
need((ROOT/'PrivateBrowser/Resources/AppIcon60x60@3x.png').exists() and (ROOT/'PrivateBrowser/Resources/AppIcon60x60@2x.png').exists(),'the actual icon files exist (generated by tools/generate-browser-icon.py before packaging)')
need('tools/generate-browser-icon.py' in ci,'the icon generator actually runs in CI before packaging')

# ---- the privacy guarantee: one ephemeral, non-persistent data store, never the real one ----
need('nonPersistentDataStore' in ctrl,'uses an ephemeral WKWebsiteDataStore -- cookies/cache/storage never touch disk')
need('WKWebsiteDataStore defaultDataStore' not in ctrl_raw,'never falls back to the real, persistent, cross-app data store')
need(ctrl.count('sharedDataStore') >= 3,'every tab (including a window.open() tab) is configured with the one shared ephemeral store, never a store of its own')
need('+ (void)purgeEphemeralData' in header and '+ (void)purgeEphemeralData' in ctrl,'a real, callable wipe exists, not just the ephemeral store\'s own eventual teardown')
need('removeDataOfTypes:forDataRecords:completionHandler:' in ctrl or 'removeDataOfTypes:' in ctrl,'the wipe actually removes data records, not just drops the Swift/ObjC reference to the store')
need('applicationWillTerminate:' in appdel and '[MYBPBBrowserController purgeEphemeralData]' in appdel_raw,'a real app quit also purges the store, belt-and-suspenders beyond ephemeral-by-construction')
need('wipeEverything' in ctrl and 'performWipe' in ctrl,'the user has a visible, explicit "wipe now" control -- not just an implicit guarantee they have to trust')
need(re.search(r'UIAlertControllerStyleAlert',ctrl) is not None and 'Wipe Everything' in ctrl_raw,'the wipe control confirms before destroying open tabs, so it can\'t be triggered by one stray tap')

# ---- privacy beyond data storage: no app-switcher snapshot leak ----
need('applicationWillResignActive:' in appdel and 'applicationDidBecomeActive:' in appdel,'covers the window before backgrounding and uncovers it only once truly active, so the app-switcher snapshot never shows page content')

# ---- blocking: deliberately NOT reimplemented here -- it rides on the existing Shield hook, same as every other browser ----
need('navigationDelegate = self' in ctrl_raw and 'UIDelegate = self' in ctrl_raw,'sets real navigation/UI delegates the ordinary WKWebView way -- the one thing the Shield hook needs in order to wrap them')
need('createWebViewWithConfiguration' in ctrl,'implements the WKUIDelegate method window.open()/target=_blank needs -- without it, the Shield hook has no popup-vs-navigation decision to intercept at all')
need(not re.search(r'contentRuleList|WKContentRuleList|adblock|blocklist',ctrl,re.I),'no second, independent ad/popup-blocking engine was written here -- blocking comes entirely from the existing Shield hook once it is injected')

# ---- basic tabs, as scoped (not zero-tab, not a full tab-grid rewrite) ----
need('MYBPBTab' in ctrl and 'MYBPBTabListController' in ctrl,'has a real multi-tab model and a switcher UI, not a single hardcoded web view')
need('tabListDidCloseIndex' in ctrl and 'commitEditingStyle' in ctrl,'a tab can be closed individually (swipe-to-delete in the switcher), not only replaced')

# ---- search/address bar doesn't invent a MYbloXX-run search backend or phone home ----
need('duckduckgo.com' in ctrl_raw,'a plain, non-MYbloXX search query (DuckDuckGo) is used for bare search terms, not a first-party endpoint')
need(not re.search(r'myxxdev\.(com|io)|mybloxx-browser-event|MYBLoopbackGET',ctrl_raw),'the browser itself makes no calls back to any MYbloXX bridge/telemetry endpoint -- it is just a WKWebView app')

print(f'\n{total-len(bad)}/{total} passed')
if bad:
    print(f'{len(bad)} FAILED:')
    for b in bad:print(' -',b)
    sys.exit(1)
