#!/usr/bin/env python3
"""Writes rules/HYBRID.md and rules/SCREENSHOTS.md from rules/canonical.json, rules/reference/screenshot-rows.json and the generated Default PAC.
Usage: generate-hybrid-report.py [outdir]   (default rules/). Decisions in SCREENSHOTS.md come from RUNNING the Default PAC, not from list membership."""
import json, subprocess, sys
from collections import OrderedDict
from pathlib import Path
root = Path(__file__).resolve().parents[1]; out = Path(sys.argv[1]) if len(sys.argv) > 1 else root / 'rules'
C = json.loads((root / 'rules/canonical.json').read_text()); H = C['hybrid']
S = json.loads((root / 'rules/reference/screenshot-rows.json').read_text()); rows = S['rows']
held, add = H['screenshot_held'], set(H['default_add'])
def covered(h, S_): p = h.split('.'); return any('.'.join(p[i:]) in S_ for i in range(len(p)))
base0 = set(C['base']['domains']) - add
probes = [['https://%s/' % (r['host'] or r['host_inferred']), r['host'] or r['host_inferred']] for r in rows]
res = json.loads(subprocess.run(['node', str(root / 'tests/pac-eval.js')], input=json.dumps({'pacs': {'D': str(root / 'layout/usr/share/mybloxx/pacs/Default.pac')}, 'probes': probes}).encode(), capture_output=True, check=True).stdout)['D']
def decide(r, v):
    h = r['host'] or r['host_inferred']; blocked = v.startswith('PROXY 127'); key = r['shown'] if r['shown'] in held else h
    if blocked and key in held: return 'CONFLICT', 'blocked but listed as held'
    if blocked: return ('blocked (added by this work)', '') if covered(h, add) and not covered(h, base0) else ('blocked (already in Default)', '')
    if key in held: return 'held (DIRECT)', held[key]
    return 'UNDECIDED', 'DIRECT with no recorded reason'
dec = [decide(r, v) for r, v in zip(rows, res)]
bad = [r['shown'] for r, d in zip(rows, dec) if d[0] in ('CONFLICT', 'UNDECIDED')]
if bad: sys.exit('screenshot rows without a consistent decision: %s' % bad)
tally = {}
for d in dec: tally[d[0]] = tally.get(d[0], 0) + 1
imgs = OrderedDict()
for r, d in zip(rows, dec): imgs.setdefault(r['image'], []).append((r, d))
ex = sorted(C['exact_allow']); unless = C.get('exact_allow_unless', {})
L = ['# Hybrid rules accounting', '', 'Generated from `rules/canonical.json` by `tools/generate-hybrid-report.py`. Do not edit by hand.', '',
     'Sources: ' + '; '.join(H['sources']) + '.', '', '| List | Count |', '|---|---|',
     '| Default additions (all modes) | %d |' % len(H['default_add']), '| noXXX-only additions | %d |' % len(H['noXXX_add']), '| Exact-host exceptions (every mode) | %d |' % len(ex),
     '| Conditional exceptions (DIRECT unless the named option is on) | %d |' % len(unless),
     '| Screenshot rows held with a stated reason | %d |' % len(held), '| CustomV55 candidates excluded | %d |' % len(H['v55_excluded']), '',
     'Screenshot accounting, row by row, is in `rules/SCREENSHOTS.md`.', '',
     '## Conditional exceptions', ''] + ['- `%s`: DIRECT in every mode except when %s is selected. Applied by the generator (`exact_allow_unless`), so it holds in all 32 combinations and the standalone files.' % (h, ' or '.join(o)) for h, o in sorted(unless.items())]
L += ['', '## Exact-host exceptions (%d)' % len(ex), '', 'Each host is tied to the CustomV55 whitelist token it comes from. V55 matches the token anywhere in a URL; an exact host cannot, so every real host of a site is listed (apex and www where the site uses both).', '',
      '| V55 token | Hosts |', '|---|---|'] + ['| `%s` | %s |' % (t, ', '.join('`%s`' % h for h in hs)) for t, hs in sorted(H['compat_tokens'].items())]
L += ['| (ad-test page) | `superadblocktest.com`, `www.superadblocktest.com` |', '',
      'Checked by `tests/policy-exceptions.js`: every host is DIRECT in all 40 PAC files; apex/www pairs are complete; `marketingturkiye.com` (a different domain) is not exempt.']
for title, items in (('Default additions (%d)' % len(H['default_add']), H['default_add']), ('noXXX-only additions (%d)' % len(H['noXXX_add']), H['noXXX_add'])):
    L += ['', '## ' + title, ''] + ['- `%s`' % x for x in items]
L += ['', '## Screenshot rows held, with the reason (%d)' % len(held), ''] + ['- `%s`: %s' % (k, v) for k, v in sorted(held.items())]
L += ['', '## CustomV55 candidates excluded (%d)' % len(H['v55_excluded']), '', H['v55_excluded_reason'], ''] + ['- `%s`' % x for x in H['v55_excluded']]
(out / 'HYBRID.md').write_text('\n'.join(L) + '\n')
M = ['# Screenshot accounting', '', 'Generated by `tools/generate-hybrid-report.py`. ' + S['note'], '',
     'Decisions are what the generated **Default** PAC returns when run, so a list entry that does not take effect cannot be counted.', '',
     '- Screenshots read: %d.' % len(imgs), '- Red rows visible: **%d** (%d read as two bands cut by a scroll edge and merged; %d truncated with an ellipsis; %d with a path that a PAC cannot see over HTTPS).' % (
         len(rows), sum(r['split_by_scroll_edge'] for r in rows), sum(r['truncated'] for r in rows), sum(r['path'] for r in rows)),
     '- Distinct hosts: %d (`track.customer.io` appears once as a host and once with `/events`).' % len({(r['host'] or r['host_inferred']) for r in rows}),
     '- Result: ' + ', '.join('%d %s' % (v, k) for k, v in sorted(tally.items())) + '.',
     '- The earlier working count of 109 was preliminary. An OCR pass found 105; reading every row as an image finds 109 again, with different hosts than the OCR pass in several rows (for example `www.awin1.com`, not `www.awint.com`).', '']
for im, items in imgs.items():
    M += ['## %s (%d rows)' % (im, len(items)), '', '| # | Row as shown | Host used | Decision | Reason / note |', '|---|---|---|---|---|']
    for r, d in items:
        h = r['host'] or r['host_inferred']; note = d[1]
        if r['truncated']: note = (note + '; ' if note else '') + 'TRUNCATED in the app; full host not visible, inferred'
        if r['split_by_scroll_edge']: note = (note + '; ' if note else '') + 'one row cut by a scroll edge'
        if r['path']: note = (note + '; ' if note else '') + 'path not visible to a PAC'
        M.append('| %d | `%s` | `%s` | %s | %s |' % (r['n'], r['shown'], h, d[0], note))
    M.append('')
(out / 'SCREENSHOTS.md').write_text('\n'.join(M) + '\n')
print('wrote HYBRID.md and SCREENSHOTS.md; %d rows; %s' % (len(rows), tally))
