#!/usr/bin/env python3
"""Generate shared Shield design tokens: CSS for the blocked page and a UIKit header for native notices."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
t=json.loads((root/'Brand/design-tokens.json').read_text())
def hexs(c):return '#%02X%02X%02X'%tuple(round(v*255) for v in c)
def block(sel,d):
    names={'background':'bg','panel':'panel','panelHighlight':'panel2','accent':'accent','muted':'muted','positive':'ok','warning':'warn','danger':'bad','rose':'rose','violetDeep':'accent-deep','text':'text'}
    lines=[f'--{n}:{hexs(d[k])}' for k,n in names.items()]
    lines.append(f"--hair:rgba({255 if sel==':root' else 0},{255 if sel==':root' else 0},{255 if sel==':root' else 0},{d['hairlineAlpha']})")
    return sel+'{'+';'.join(lines)+'}'
css=block(':root',t['dark'])+'\n@media(prefers-color-scheme:light){'+block(':root',t['light']).replace('rgba(255,255,255','rgba(0,0,0')+'}'
css+='\n:root{--r-card:%dpx;--r-sheet:%dpx;--r-btn:%dpx;--r-tile:%dpx}'%(t['radius']['card'],t['radius']['sheet'],t['radius']['button'],t['radius']['tile'])
(root/'BlockedServer/tokens.generated.css').write_text(css+'\n')
def uic(c,a=1):return '[UIColor colorWithRed:%g green:%g blue:%g alpha:%g]'%(c[0],c[1],c[2],a)
h='#pragma once\n// Generated by tools/generate-design-tokens.py from Brand/design-tokens.json. Do not edit.\n#import <UIKit/UIKit.h>\n'
for k in ('background','panel','panelHighlight','accent','muted','positive','warning','danger'):
    h+='static inline UIColor *MYBShield%s(void){return %s;}\n'%(k[0].upper()+k[1:],uic(t['dark'][k]))
h+='static inline UIColor *MYBShieldHairline(void){return [UIColor colorWithWhite:1 alpha:%g];}\n'%t['dark']['hairlineAlpha']
h+='#define MYBShieldCardRadius %d.0\n#define MYBShieldSheetRadius %d.0\n#define MYBShieldButtonRadius %d.0\n'%(t['radius']['card'],t['radius']['sheet'],t['radius']['button'])
(root/'Shared/MYBShieldTheme.h').write_text(h)
print('design tokens generated')
